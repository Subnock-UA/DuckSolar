"""Structural extension contracts; transport, protocol and UI remain independent."""
from typing import Protocol,Any
from .models import DeviceDefinition, ParameterSpec, PollTask

class InverterDriver(Protocol):
    id: str
    device_code: int
    read_requests: dict[bytes,str]
    identity_names: tuple[str,...]
    specs: list[ParameterSpec]
    def poll_plan(self) -> list[PollTask]: ...
    def decode_response(self,payload:bytes,operation:str) -> Any: ...
    def decode_update(self,task:PollTask,response:Any) -> dict: ...
    def valid_response(self,payload:bytes) -> bool: ...
    def parameter_catalog(self,raw:dict) -> list[dict]: ...
    def parameter_rows_from_raw(self,raw:dict) -> list[dict]: ...
    def identity(self,raw:dict) -> dict: ...
    def descriptor(self,definition:DeviceDefinition,raw:dict) -> dict: ...
    def normalized(self,values:dict) -> dict: ...

class DeviceTransport(Protocol):
    connected: bool
    connection_id: str
    measurement_connection_id: str
    def transact(self,request:bytes) -> bytes: ...
    def snapshot_status(self): ...
    def send_redirect(self) -> str: ...

class LoggerAdapter(Protocol):
    capabilities: dict
    connected: bool
    connection_id: str
    def create_channel(self,definition:DeviceDefinition) -> DeviceTransport: ...
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def snapshot_status(self): ...
